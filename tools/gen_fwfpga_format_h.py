#!/usr/bin/env python3
"""Render fw2_fwfpga_format.h for the firmware from fwfpga_format.py's layout table.

    python tools/gen_fwfpga_format_h.py                 # writes firmware/generated/fw2_fwfpga_format.h
    python tools/gen_fwfpga_format_h.py --check         # exit 1 if the checked-in header is stale
    python tools/gen_fwfpga_format_h.py -o path.h

The header is C99/C++ (packed struct, static_asserts on every offset, enums for
kind / capabilities / clock codes / IO modes, the ID block layout, a
table-driven zlib-compatible CRC-32 and `fw2_fwfpga_header_valid()`).
Regenerate it in the same commit as any layout change.
"""
import sys
import zlib
from pathlib import Path

import design_toml
import fwfpga_format as ff
import gen_design_id as gid
import profile as iop

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = REPO_ROOT / "firmware" / "generated" / "fw2_fwfpga_format.h"


def crc32_table():
    table = []
    for n in range(256):
        c = n
        for _ in range(8):
            c = (0xEDB88320 ^ (c >> 1)) if c & 1 else c >> 1
        table.append(c)
    # sanity: the table must reproduce zlib
    assert _crc32_with(table, b"123456789") == zlib.crc32(b"123456789")
    return table


def _crc32_with(table, data, crc=0):
    crc ^= 0xFFFFFFFF
    for b in data:
        crc = table[(crc ^ b) & 0xFF] ^ (crc >> 8)
    return crc ^ 0xFFFFFFFF


def _struct_member(name, ctype):
    if "[" in ctype:
        base, n = ctype.split("[")
        return f"    {base} {name}[{n};"
    return f"    {ctype} {name};"


def render():
    L = []
    w = L.append
    w("/* fw2_fwfpga_format.h -- GENERATED by tools/gen_fwfpga_format_h.py from tools/fwfpga_format.py.")
    w(" * Do not edit; regenerate in the same commit as any layout change.")
    w(" *")
    w(" * The .fwfpga container: 256-byte little-endian header, optional host-only JSON manifest,")
    w(" * then the iCE40 bitstream. CRC-32 is zlib's (poly 0xEDB88320 reflected, init/xorout 0xFFFFFFFF).")
    w(" */")
    w("#ifndef FW2_FWFPGA_FORMAT_H")
    w("#define FW2_FWFPGA_FORMAT_H")
    w("")
    w("#include <stdbool.h>")
    w("#include <stddef.h>")
    w("#include <stdint.h>")
    w("#include <string.h>")
    w("")
    w("#ifdef __cplusplus")
    w("extern \"C\" {")
    w("#define FW2_STATIC_ASSERT(cond, msg) static_assert(cond, msg)")
    w("#else")
    w("#define FW2_STATIC_ASSERT(cond, msg) _Static_assert(cond, msg)")
    w("#endif")
    w("")
    w("/* ---- header constants ---- */")
    magic = ", ".join(f"0x{b:02X}" for b in ff.MAGIC)
    w(f"#define FW2_FWFPGA_MAGIC_BYTES {{ {magic} }}   /* \"FW2FPGA\\0\" */")
    w(f"#define FW2_FWFPGA_MAGIC_LEN {len(ff.MAGIC)}")
    w(f"#define FW2_FWFPGA_FORMAT_VERSION {ff.FORMAT_VERSION}u")
    w(f"#define FW2_FWFPGA_CONTRACT_VERSION {ff.CONTRACT_VERSION}u")
    w(f"#define FW2_FWFPGA_HEADER_LEN {ff.HEADER_LEN}u")
    w(f"#define FW2_FWFPGA_HEADER_CRC_SPAN {ff.HEADER_CRC_SPAN}u   /* header_crc32 covers bytes 0..{ff.HEADER_CRC_SPAN - 1} */")
    w(f"#define FW2_FWFPGA_NAME_LEN {ff.NAME_LEN}u            /* NUL padded, <= {ff.NAME_LEN - 1} chars */")
    w(f"#define FW2_FWFPGA_DESCRIPTION_LEN {ff.DESCRIPTION_LEN}u    /* NUL padded, <= {ff.DESCRIPTION_LEN - 1} chars */")
    w(f"#define FW2_FWFPGA_RESERVED_LEN {ff.RESERVED_LEN}u")
    w(f"#define FW2_FWFPGA_STOCK_DESIGN_ID 0x{ff.STOCK_DESIGN_ID:04X}u  /* kind == STOCK: no ID block expected */")
    w(f"#define FW2_FWFPGA_BITSTREAM_MIN {ff.BITSTREAM_MIN}u")
    w(f"#define FW2_FWFPGA_BITSTREAM_MAX {ff.BITSTREAM_MAX}u")
    pre = ", ".join(f"0x{b:02X}" for b in ff.ICE40_PREAMBLE)
    w(f"#define FW2_ICE40_PREAMBLE_BYTES {{ {pre} }}")
    w(f"#define FW2_ICE40_PREAMBLE_WINDOW {ff.PREAMBLE_WINDOW}u   /* preamble must appear within the first N bitstream bytes */")
    w("")
    w("/* ---- field offsets (bytes from the start of the header) ---- */")
    for name, off, size, _, _ in ff.FIELDS:
        w(f"#define FW2_FWFPGA_OFF_{name.upper()} {off}u   /* {size} byte{'s' if size != 1 else ''} */")
    w("")
    w("/* ---- enums ---- */")
    w("typedef enum fw2_fwfpga_kind {")
    for k, v in design_toml.KINDS.items():
        w(f"    FW2_FWFPGA_KIND_{k.upper()} = {v},")
    w("} fw2_fwfpga_kind_t;")
    w("")
    w("typedef enum fw2_fwfpga_cap {")
    for k, v in design_toml.CAPABILITIES.items():
        w(f"    FW2_CAP_{k} = 0x{v:02X},")
    w(f"    FW2_CAP_ALL = 0x{sum(design_toml.CAPABILITIES.values()):02X},")
    w("} fw2_fwfpga_cap_t;")
    w("")
    w("typedef enum fw2_clock_code {")
    for code, hz in design_toml.CLOCK_CODES.items():
        w(f"    FW2_CLOCK_CODE_{hz // 1000}KHZ = {code},   /* {hz} Hz */")
    w(f"    FW2_CLOCK_CODE_COUNT = {len(design_toml.CLOCK_CODES)},")
    w("} fw2_clock_code_t;")
    w("")
    w("static const uint32_t FW2_CLOCK_CODE_HZ[FW2_CLOCK_CODE_COUNT] = {")
    w("    " + ", ".join(f"{hz}u" for hz in design_toml.CLOCK_CODES.values()))
    w("};")
    w("")
    w("/* IO profile: ten signals x 3 bits, signal i in bits [3i+2:3i] of io_profile. */")
    w("typedef enum fw2_iop_mode {")
    for k, v in iop.MODES.items():
        row = iop.MODE_TABLE[k]
        w(f"    FW2_IOP_{k} = {v},   /* RP {row['rp_dir']}, _Rp {row['fpga_rp_dir']}, _Out {row['fpga_out_dir']}, DIR {row['shifter_dir']} */")
    w("    FW2_IOP_INVALID = 7,")
    w("} fw2_iop_mode_t;")
    w("")
    w("typedef enum fw2_iop_signal {")
    for i, (sig, label, gpio) in enumerate(iop.SIGNALS):
        w(f"    FW2_SIG_{sig.upper()} = {i},   /* {label}, RP2350 GPIO{gpio} */")
    w(f"    FW2_SIG_COUNT = {len(iop.SIGNALS)},")
    w("} fw2_iop_signal_t;")
    w("")
    w(f"#define FW2_IOP_BITS {iop.MODE_BITS}u")
    w(f"#define FW2_IOP_MASK 0x{iop.PROFILE_MASK:08X}u   /* bits 30 and 31 are always zero */")
    w("#define FW2_IOP_MODE(packed, sig) ((fw2_iop_mode_t)(((packed) >> (FW2_IOP_BITS * (uint32_t)(sig))) & 7u))")
    w("")
    w("static const uint8_t FW2_SIG_RP_GPIO[FW2_SIG_COUNT] = { " + ", ".join(str(s[2]) for s in iop.SIGNALS) + " };")
    w("")
    w("/* ---- the header struct (packed, little-endian on the wire; parse with fw2_fwfpga_header_parse) ---- */")
    w("#pragma pack(push, 1)")
    w("typedef struct fw2_fwfpga_header {")
    for name, off, size, _, ctype in ff.FIELDS:
        w(_struct_member(name, ctype))
    w("} fw2_fwfpga_header_t;")
    w("#pragma pack(pop)")
    w("")
    w(f"FW2_STATIC_ASSERT(sizeof(fw2_fwfpga_header_t) == {ff.HEADER_LEN}, \"fw2_fwfpga_header_t must be {ff.HEADER_LEN} bytes\");")
    for name, off, size, _, _ in ff.FIELDS:
        w(f"FW2_STATIC_ASSERT(offsetof(fw2_fwfpga_header_t, {name}) == {off}, \"{name} offset\");")
    for name, off, size, _, _ in ff.FIELDS:
        w(f"FW2_STATIC_ASSERT(sizeof(((fw2_fwfpga_header_t *)0)->{name}) == {size}, \"{name} size\");")
    w("")
    w("/* ---- ID block: 16 read-only bytes at register 0x70 of an fw2_shell design ---- */")
    w(f"#define FW2_IDBLK_BASE 0x{gid.ID_BLOCK_BASE:02X}u")
    w(f"#define FW2_IDBLK_LEN {gid.ID_BLOCK_LEN}u")
    idm = ", ".join(f"0x{b:02X}" for b in gid.ID_MAGIC)
    w(f"#define FW2_IDBLK_MAGIC_BYTES {{ {idm} }}   /* \"FW2F\" */")
    for name, off, size in (("MAGIC", 0, 4), ("CONTRACT_VERSION", 4, 1), ("DESIGN_ID", 5, 2),
                            ("DESIGN_VERSION", 7, 2), ("CAPABILITIES", 9, 1), ("CLOCK_CODE", 10, 1),
                            ("IO_PROFILE", 11, 4), ("CHECKSUM", 15, 1)):
        w(f"#define FW2_IDBLK_OFF_{name} {off}u   /* {size} byte{'s' if size != 1 else ''}, register 0x{gid.ID_BLOCK_BASE + off:02X} */")
    w("")
    w("/* Which header field an ID block disagrees with (fw2_idblk_compare). */")
    w("typedef enum fw2_idblk_mismatch {")
    w("    FW2_IDBLK_MATCH = 0,")
    w("    FW2_IDBLK_BAD_MAGIC,")
    w("    FW2_IDBLK_BAD_CHECKSUM,")
    w("    FW2_IDBLK_MISMATCH_CONTRACT_VERSION,")
    w("    FW2_IDBLK_MISMATCH_DESIGN_ID,")
    w("    FW2_IDBLK_MISMATCH_DESIGN_VERSION,")
    w("    FW2_IDBLK_MISMATCH_CAPABILITIES,")
    w("    FW2_IDBLK_MISMATCH_CLOCK_CODE,")
    w("    FW2_IDBLK_MISMATCH_IO_PROFILE,")
    w("} fw2_idblk_mismatch_t;")
    w("")
    w("/* ---- little-endian readers ---- */")
    w("static inline uint16_t fw2_rd16(const uint8_t *p) { return (uint16_t)(p[0] | ((uint16_t)p[1] << 8)); }")
    w("static inline uint32_t fw2_rd32(const uint8_t *p) {")
    w("    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);")
    w("}")
    w("")
    w("/* ---- zlib-compatible CRC-32 (table driven). Use the firmware's own routine if it has one;")
    w("   pass it as fw2_crc32_fn, or NULL to use this. Seed with 0 and chain the return value. ---- */")
    w("typedef uint32_t (*fw2_crc32_fn)(uint32_t crc, const uint8_t *data, size_t len);")
    w("")
    w("static const uint32_t FW2_CRC32_TABLE[256] = {")
    tab = crc32_table()
    for i in range(0, 256, 8):
        w("    " + ", ".join(f"0x{v:08X}" for v in tab[i:i + 8]) + ",")
    w("};")
    w("")
    w("static inline uint32_t fw2_crc32_update(uint32_t crc, const uint8_t *data, size_t len) {")
    w("    crc = ~crc;")
    w("    for (size_t i = 0; i < len; i++) crc = FW2_CRC32_TABLE[(crc ^ data[i]) & 0xFFu] ^ (crc >> 8);")
    w("    return ~crc;")
    w("}")
    w("")
    w("/* ---- parse / validate ---- */")
    w("")
    w("/* Copy the 256 raw header bytes into the struct, field by field (endian safe). */")
    w("static inline void fw2_fwfpga_header_parse(const uint8_t *raw, fw2_fwfpga_header_t *out) {")
    for name, off, size, code, ctype in ff.FIELDS:
        if "[" in ctype:
            w(f"    memcpy(out->{name}, raw + {off}, {size});")
        elif size == 1:
            w(f"    out->{name} = raw[{off}];")
        elif size == 2:
            w(f"    out->{name} = fw2_rd16(raw + {off});")
        else:
            w(f"    out->{name} = fw2_rd32(raw + {off});")
    w("}")
    w("")
    w("/* Magic, format_version, header_len and header CRC-32 over bytes 0..251. This is the gate the")
    w("   firmware must pass BEFORE touching CRESET; it needs only the first 256 bytes of the file. */")
    w("static inline bool fw2_fwfpga_header_valid(const uint8_t *raw256, fw2_crc32_fn crc32) {")
    w("    static const uint8_t magic[FW2_FWFPGA_MAGIC_LEN] = FW2_FWFPGA_MAGIC_BYTES;")
    w("    if (memcmp(raw256, magic, FW2_FWFPGA_MAGIC_LEN) != 0) return false;")
    w("    if (raw256[FW2_FWFPGA_OFF_FORMAT_VERSION] != FW2_FWFPGA_FORMAT_VERSION) return false;")
    w("    if (fw2_rd16(raw256 + FW2_FWFPGA_OFF_HEADER_LEN) != FW2_FWFPGA_HEADER_LEN) return false;")
    w("    uint32_t want = fw2_rd32(raw256 + FW2_FWFPGA_OFF_HEADER_CRC32);")
    w("    uint32_t got = crc32 ? crc32(0, raw256, FW2_FWFPGA_HEADER_CRC_SPAN)")
    w("                         : fw2_crc32_update(0, raw256, FW2_FWFPGA_HEADER_CRC_SPAN);")
    w("    return want == got;")
    w("}")
    w("")
    w("/* Field-level sanity after fw2_fwfpga_header_valid(): contract version, kind/design_id rules,")
    w("   profile encoding, reserved bytes. Returns NULL when fine, else a short reason. */")
    w("static inline const char *fw2_fwfpga_header_check_fields(const fw2_fwfpga_header_t *h) {")
    w("    if (h->contract_version != FW2_FWFPGA_CONTRACT_VERSION) return \"contract_version\";")
    w("    if (h->kind != FW2_FWFPGA_KIND_USER && h->kind != FW2_FWFPGA_KIND_STOCK) return \"kind\";")
    w("    if (h->kind == FW2_FWFPGA_KIND_STOCK && h->design_id != FW2_FWFPGA_STOCK_DESIGN_ID) return \"stock design_id\";")
    w("    if (h->kind == FW2_FWFPGA_KIND_USER && h->design_id == FW2_FWFPGA_STOCK_DESIGN_ID) return \"design_id reserved\";")
    w("    if (h->design_version > 999) return \"design_version\";")
    w("    if (h->capabilities & (uint8_t)~FW2_CAP_ALL) return \"capabilities\";")
    w("    if (h->clock_code >= FW2_CLOCK_CODE_COUNT) return \"clock_code\";")
    w("    if (h->io_profile & ~FW2_IOP_MASK) return \"io_profile high bits\";")
    w("    for (uint32_t s = 0; s < FW2_SIG_COUNT; s++)")
    w("        if (FW2_IOP_MODE(h->io_profile, s) == FW2_IOP_INVALID) return \"io_profile mode 7\";")
    w("    for (size_t i = 0; i < FW2_FWFPGA_RESERVED_LEN; i++) if (h->reserved[i]) return \"reserved\";")
    w("    if (h->name[0] == 0) return \"name\";")
    w("    if (h->name[FW2_FWFPGA_NAME_LEN - 1] != 0) return \"name not terminated\";")
    w("    if (h->description[FW2_FWFPGA_DESCRIPTION_LEN - 1] != 0) return \"description not terminated\";")
    w("    if (h->bitstream_len < FW2_FWFPGA_BITSTREAM_MIN || h->bitstream_len > FW2_FWFPGA_BITSTREAM_MAX) return \"bitstream_len\";")
    w("    return NULL;")
    w("}")
    w("")
    w("/* True if the iCE40 preamble appears in the first FW2_ICE40_PREAMBLE_WINDOW bytes of a bitstream. */")
    w("static inline bool fw2_ice40_has_preamble(const uint8_t *bits, size_t len) {")
    w("    static const uint8_t pre[4] = FW2_ICE40_PREAMBLE_BYTES;")
    w("    size_t n = len < FW2_ICE40_PREAMBLE_WINDOW ? len : FW2_ICE40_PREAMBLE_WINDOW;")
    w("    for (size_t i = 0; i + 4 <= n; i++) if (memcmp(bits + i, pre, 4) == 0) return true;")
    w("    return false;")
    w("}")
    w("")
    w("/* ---- ID block helpers ---- */")
    w("static inline uint8_t fw2_idblk_checksum(const uint8_t *blk) {")
    w("    uint8_t x = 0;")
    w("    for (size_t i = 0; i < FW2_IDBLK_LEN - 1; i++) x ^= blk[i];")
    w("    return x;")
    w("}")
    w("")
    w("/* Build the 16 bytes the fabric must answer for this header (what tools/gen_design_id.py bakes in). */")
    w("static inline void fw2_idblk_from_header(const fw2_fwfpga_header_t *h, uint8_t *blk16) {")
    w("    static const uint8_t magic[4] = FW2_IDBLK_MAGIC_BYTES;")
    w("    memcpy(blk16, magic, 4);")
    w("    blk16[FW2_IDBLK_OFF_CONTRACT_VERSION] = h->contract_version;")
    w("    blk16[FW2_IDBLK_OFF_DESIGN_ID] = (uint8_t)h->design_id;")
    w("    blk16[FW2_IDBLK_OFF_DESIGN_ID + 1] = (uint8_t)(h->design_id >> 8);")
    w("    blk16[FW2_IDBLK_OFF_DESIGN_VERSION] = (uint8_t)h->design_version;")
    w("    blk16[FW2_IDBLK_OFF_DESIGN_VERSION + 1] = (uint8_t)(h->design_version >> 8);")
    w("    blk16[FW2_IDBLK_OFF_CAPABILITIES] = h->capabilities;")
    w("    blk16[FW2_IDBLK_OFF_CLOCK_CODE] = h->clock_code;")
    w("    for (int i = 0; i < 4; i++) blk16[FW2_IDBLK_OFF_IO_PROFILE + i] = (uint8_t)(h->io_profile >> (8 * i));")
    w("    blk16[FW2_IDBLK_OFF_CHECKSUM] = fw2_idblk_checksum(blk16);")
    w("}")
    w("")
    w("/* Compare the ID block read from the fabric with the container header. FW2_IDBLK_MATCH (0) or the")
    w("   first disagreeing field; the firmware restores stock and names that field in its reply. */")
    w("static inline fw2_idblk_mismatch_t fw2_idblk_compare(const uint8_t *blk16, const fw2_fwfpga_header_t *h) {")
    w("    static const uint8_t magic[4] = FW2_IDBLK_MAGIC_BYTES;")
    w("    if (memcmp(blk16, magic, 4) != 0) return FW2_IDBLK_BAD_MAGIC;")
    w("    if (fw2_idblk_checksum(blk16) != blk16[FW2_IDBLK_OFF_CHECKSUM]) return FW2_IDBLK_BAD_CHECKSUM;")
    w("    if (blk16[FW2_IDBLK_OFF_CONTRACT_VERSION] != h->contract_version) return FW2_IDBLK_MISMATCH_CONTRACT_VERSION;")
    w("    if (fw2_rd16(blk16 + FW2_IDBLK_OFF_DESIGN_ID) != h->design_id) return FW2_IDBLK_MISMATCH_DESIGN_ID;")
    w("    if (fw2_rd16(blk16 + FW2_IDBLK_OFF_DESIGN_VERSION) != h->design_version) return FW2_IDBLK_MISMATCH_DESIGN_VERSION;")
    w("    if (blk16[FW2_IDBLK_OFF_CAPABILITIES] != h->capabilities) return FW2_IDBLK_MISMATCH_CAPABILITIES;")
    w("    if (blk16[FW2_IDBLK_OFF_CLOCK_CODE] != h->clock_code) return FW2_IDBLK_MISMATCH_CLOCK_CODE;")
    w("    if (fw2_rd32(blk16 + FW2_IDBLK_OFF_IO_PROFILE) != h->io_profile) return FW2_IDBLK_MISMATCH_IO_PROFILE;")
    w("    return FW2_IDBLK_MATCH;")
    w("}")
    w("")
    w("#ifdef __cplusplus")
    w("}")
    w("#endif")
    w("#endif /* FW2_FWFPGA_FORMAT_H */")
    return "\n".join(L) + "\n"


def main(argv=None):
    import argparse
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("-o", "--out", default=str(DEFAULT_OUT))
    p.add_argument("--check", action="store_true", help="exit 1 if the file on disk differs from the generator")
    a = p.parse_args(argv)
    text = render()
    out = Path(a.out)
    if a.check:
        if not out.exists() or out.read_text(encoding="ascii") != text:
            print(f"STALE: {out} differs from gen_fwfpga_format_h.py output; regenerate", file=sys.stderr)
            return 1
        print(f"OK: {out} is current")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="ascii", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
