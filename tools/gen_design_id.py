#!/usr/bin/env python3
"""design.toml -> fw2_design_id.vh (the ID block constants baked into the fabric).

    python tools/gen_design_id.py designs/hello_blink/design.toml -o build/designs/hello_blink/fw2_design_id.vh
    python tools/gen_design_id.py designs/hello_blink/design.toml --bytes      # the 16 ID-block bytes as hex

ID block, 16 read-only bytes at register 0x70 (docs/drivers/shell.md):

    0x70..0x73  "FW2F"            0x46 0x57 0x32 0x46
    0x74        contract_version  1
    0x75..0x76  design_id         u16 LE
    0x77..0x78  design_version    u16 LE (000..999)
    0x79        capabilities      bit field
    0x7A        clock_code
    0x7B..0x7E  io_profile        u32 LE, 10 x 3-bit (tools/profile.py)
    0x7F        checksum          XOR of bytes 0x70..0x7E

The same Design object feeds pack_fwfpga.py, so the container header and the
fabric's ID block come from one source; check_container.py asserts equality.
"""
import struct
import sys
from pathlib import Path

import design_toml
import profile as iop

ID_MAGIC = b"FW2F"
ID_BLOCK_BASE = 0x70
ID_BLOCK_LEN = 16


def id_block_fields(design):
    """The ID block as a dict of integers (what the firmware compares against the header)."""
    return {
        "contract_version": design_toml.CONTRACT_VERSION,
        "design_id": design.design_id,
        "design_version": design.version,
        "capabilities": design.caps_byte,
        "clock_code": design.clock_code,
        "io_profile": design.io_profile_packed,
    }


def id_block_bytes(design_id, design_version, capabilities, clock_code, io_profile,
                   contract_version=design_toml.CONTRACT_VERSION):
    """The 16 bytes at 0x70..0x7F for the given field values."""
    body = ID_MAGIC + struct.pack("<BHHBBI", contract_version, design_id, design_version,
                                  capabilities, clock_code, io_profile)
    assert len(body) == ID_BLOCK_LEN - 1
    return body + bytes([xor_checksum(body)])


def id_block_for(design):
    return id_block_bytes(**id_block_fields(design))


def xor_checksum(data):
    value = 0
    for b in data:
        value ^= b
    return value


def parse_id_block(block):
    """16 bytes -> dict, verifying magic and checksum. Raises ValueError."""
    if len(block) != ID_BLOCK_LEN:
        raise ValueError(f"ID block must be {ID_BLOCK_LEN} bytes, got {len(block)}")
    if block[:4] != ID_MAGIC:
        raise ValueError(f"ID block magic {block[:4]!r} != {ID_MAGIC!r} (no fw2_shell ID block in the fabric)")
    if xor_checksum(block[:15]) != block[15]:
        raise ValueError(f"ID block checksum 0x{block[15]:02X} != computed 0x{xor_checksum(block[:15]):02X}")
    contract_version, design_id, design_version, caps, clock_code, io_profile = struct.unpack("<BHHBBI", block[4:15])
    return {
        "contract_version": contract_version, "design_id": design_id, "design_version": design_version,
        "capabilities": caps, "clock_code": clock_code, "io_profile": io_profile,
    }


def render_vh(design):
    f = id_block_fields(design)
    block = id_block_for(design)
    lines = [
        "// fw2_design_id.vh -- GENERATED by tools/gen_design_id.py from design.toml. Do not edit.",
        f"// design: {design.name} v{design.version_str} ({design.kind}) -- {design.description}",
        f"// io_profile: {iop.summary(design.io_profile)}",
        f"// ID block bytes 0x70..0x7F: {block.hex(' ')}",
        "`ifndef FW2_DESIGN_ID_VH",
        "`define FW2_DESIGN_ID_VH",
        f"`define FW2_DESIGN_ID        16'd{f['design_id']}",
        f"`define FW2_DESIGN_VERSION   16'd{f['design_version']}",
        f"`define FW2_DESIGN_CAPS      8'h{f['capabilities']:02X}",
        f"`define FW2_DESIGN_CLOCK_CODE 8'd{f['clock_code']}",
        f"`define FW2_DESIGN_CLOCK_HZ  {design.clock_hz}",
        f"`define FW2_DESIGN_IO_PROFILE 32'h{f['io_profile']:08X}",
        f"`define FW2_DESIGN_CHECKSUM  8'h{block[15]:02X}",
        f"`define FW2_DESIGN_CONTRACT_VERSION 8'd{f['contract_version']}",
    ]
    for sig in iop.SIGNAL_NAMES:
        lines.append(f"`define FW2_IOP_{sig.upper()} 3'd{iop.MODES[design.io_profile[sig]]}")
    lines.append("`endif // FW2_DESIGN_ID_VH")
    return "\n".join(lines) + "\n"


def write_vh(design, out_path):
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    text = render_vh(design)
    if not out_path.exists() or out_path.read_text(encoding="ascii") != text:
        out_path.write_text(text, encoding="ascii", newline="\n")
    return out_path


def main(argv=None):
    import argparse
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("design", help="design.toml or design directory")
    p.add_argument("-o", "--out", help="output .vh (default: stdout)")
    p.add_argument("--bytes", action="store_true", help="print the 16 ID-block bytes as hex instead")
    a = p.parse_args(argv)
    try:
        design = design_toml.load_design(a.design)
    except design_toml.DesignError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if a.bytes:
        print(id_block_for(design).hex(" "))
        return 0
    if a.out:
        write_vh(design, a.out)
        print(f"wrote {a.out}")
    else:
        sys.stdout.write(render_vh(design))
    return 0


if __name__ == "__main__":
    sys.exit(main())
